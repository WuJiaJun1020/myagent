import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { spawn } from "node:child_process";
import { createRequire } from "node:module";
const out=resolve('.cache/theme-acceptance');
await mkdir(out,{recursive:true});
await build({entryPoints:['scripts/theme-acceptance/renderer.tsx'],outfile:resolve(out,'renderer.js'),bundle:true,platform:'browser',format:'iife',jsx:'automatic',define:{'process.env.NODE_ENV':'"production"'},logLevel:'silent'});
const builtHtml=await readFile('dist/renderer/index.html','utf8');
const css=builtHtml.match(/href="(\.\/assets\/[^"<>]+\.css)"/)[1];
const cssUrl=pathToFileURL(resolve('dist/renderer',css)).href;
await writeFile(resolve(out,'index.html'),`<!doctype html><html><head><meta charset="utf-8"><link rel="stylesheet" href="renderer.css"><link rel="stylesheet" href="${cssUrl}"></head><body><div id="root"></div><script src="renderer.js"></script></body></html>`);
const electron=createRequire(import.meta.url)('electron');
const env={...process.env}; delete env.ELECTRON_RUN_AS_NODE;
const child=spawn(electron,['scripts/theme-acceptance/main.cjs',out],{stdio:'inherit',windowsHide:true,env});
child.on('exit',code=>process.exitCode=code??1);
